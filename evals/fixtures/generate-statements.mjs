function bucket(timeline, bank, cards) {
  const statements = [];
  const prev = Object.fromEntries(cards.map((c) => [c.key, randCents(300, 900)]));
  MONTHS.forEach(({ y, m }, idx) => {
    const stmtDate = d(y, m, bank === "DBS" ? 14 : 13);
    const prevStmt = d(m === 0 ? y - 1 : y, (m + 11) % 12, bank === "DBS" ? 14 : 13);
    const from = addDays(prevStmt, 1);
    const prevDue = addDays(prevStmt, bank === "DBS" ? 25 : 19);
    const st = {
      bank,
      idx,
      stmtDate,
      dueDate: addDays(stmtDate, bank === "DBS" ? 25 : 19),
      cards: [],
    };
    for (const card of cards) {
      const rows = [];
      if (prev[card.key] > 0) {
        const payDate = bank === "DBS" ? addDays(prevDue, -1) : prevDue;
        rows.push({
          txnDate: payDate,
          postDate: bank === "UOB" ? payDate : null,
          desc: bank === "DBS" ? `AUTOPAY AC#${"0".repeat(16)}` : "GIRO PAYMENT",
          cents: -prev[card.key],
          cat: "Transfers",
          kind: "card_payment",
          ref: bank === "DBS" ? digits(23) : null,
        });
      }
      if (card.key === "uob-cb") {
        rows.push({
          txnDate: addDays(stmtDate, -2),
          postDate: addDays(stmtDate, -1),
          desc: `${card.product} Card Cashback`,
          cents: -randCents(0.5, 6),
          cat: "Cashback & Rewards",
          kind: "cashback",
          ref: null,
        });
      }
      // Bucket by post date (UOB) or transaction date (DBS). Document order:
      // payment/cashback credits, then charges by date; DBS supplementary rows last.
      const charges = timeline
        .filter((r) => r.card === card.key)
        .filter((r) => (r.postDate ?? r.txnDate) >= from && (r.postDate ?? r.txnDate) <= stmtDate)
        .map((r) => ({ ...r, kind: r.kind ?? "charge" }))
        .sort(
          (a, b) =>
            a.txnDate - b.txnDate ||
            (a.postDate ?? 0) - (b.postDate ?? 0) ||
            (a.supp ? 1 : 0) - (b.supp ? 1 : 0),
        );
      rows.push(...charges.filter((r) => !r.supp), ...charges.filter((r) => r.supp));
      const total = prev[card.key] + rows.reduce((s, r) => s + r.cents, 0);
      st.cards.push({ card, previous: prev[card.key], rows, total });
      prev[card.key] = total;
    }
    st.total = st.cards.reduce((s, c) => s + c.total, 0);
    st.minimum =
      bank === "DBS" ? minPay(st.total) : st.cards.reduce((s, c) => s + minPay(c.total), 0);
    statements.push(st);
  });
  return statements;
}

// ---------------------------------------------------------------- PDF layout

class Layout {
  constructor(pdf, fonts, { onNewPage, top = 770, bottom = 90 }) {
    Object.assign(this, { pdf, fonts, onNewPage, top, bottom });
    this.pages = [];
    this.page = null;
    this.y = 0;
  }
  newPage() {
    this.page = this.pdf.addPage([595.28, 841.89]);
    this.pages.push(this.page);
    this.y = this.top;
    this.onNewPage?.(this);
  }
  ensure(h) {
    if (!this.page || this.y - h < this.bottom) this.newPage();
  }
  text(
    s,
    x,
    { size = 8, bold = false, right = false, y = this.y, color = rgb(0.1, 0.1, 0.1) } = {},
  ) {
    const font = bold ? this.fonts.bold : this.fonts.reg;
    const w = font.widthOfTextAtSize(s, size);
    this.page.drawText(s, { x: right ? x - w : x, y, size, font, color });
  }
  line(h = 11) {
    this.y -= h;
  }
}

